import assert from 'node:assert/strict'
const core=await import('../src/services/ai/story-core.js').catch(()=>({}))
assert.equal(typeof core.createStoryDocument,'function','story authoring must start from an empty chapter')
const {createStoryDocument:create,storyRequest:request,appendStoryTurn:append,editStoryDocument:edit,selectStoryVariant:select,assertStoryReview:review,canAutoAdvance:auto}=core
const doc=create({workId:'w',chapterId:'c',text:'',sourceHash:'h'})
assert.equal(request(doc,'').type,'chapter.story')
assert.equal(request(doc,'').story.text,'')
assert.equal(request(doc,'').story.controlPolicy,'narrator')
assert.equal(request(doc,'').story.operation,'advance')
append(doc,{id:'t1',text:'雾在港口升起。',source:{bookRevision:'b'}})
assert.equal(doc.text,'雾在港口升起。')
assert.equal(request(doc,'').story.text,doc.text)
edit(doc,{text:'雾散了，船离开港口。',html:'<p>雾散了，船离开港口。</p>'})
assert.equal(request(doc,'继续').story.text,'雾散了，船离开港口。')
doc.review={sourceDraft:{id:doc.id,revision:doc.revision,contentHash:core.storyHash(doc.text)},items:[]}
assert.equal(review(doc),true)
append(doc,{id:'t2',text:'岸上的人挥了挥手。'})
assert.throws(()=>review(doc),/审稿|变化/)
const first=doc.turns.at(-1)
append(doc,{id:'v2',text:'岸上只剩一盏灯。'}, {regenerate:true})
assert.equal(doc.turns.length,2)
assert.equal(doc.turns.at(-1).variants.length,2)
assert(!doc.text.includes('挥了挥手'))
select(doc,0)
assert.equal(doc.text,'雾散了，船离开港口。\n\n岸上的人挥了挥手。')
edit(doc,{text:doc.text+'他转过身。',html:''})
assert.throws(()=>select(doc,1),/编辑|版本/,'switching cannot erase manual edits')
assert.throws(()=>append(doc,{id:'late',text:'迟到'},{regenerate:true}),/编辑|版本/)
assert.equal(auto({round:0,maxRounds:6,remaining:20000,targetWords:3000},doc),true)
assert.equal(auto({round:6,maxRounds:6,remaining:20000,targetWords:3000},doc),false)
assert.equal(auto({round:0,maxRounds:6,remaining:10,targetWords:3000},doc),false)
assert.throws(()=>create({workId:'',chapterId:'c'}),/作品|章节/)
const {recoverMemoryJob}=await import('../src/services/ai/memory-queue-core.js')
const recovered=recoverMemoryJob(doc)
assert.notEqual(recovered.incarnation,doc.incarnation,'restoring a story document must invalidate old windows')
assert.equal(recoverMemoryJob({type:'story-run',status:'running',owner:'old'}).status,'interrupted')
assert.equal(typeof core.storyPreview,'function','streaming prose must not expose raw tool JSON')
assert.equal(core.storyPreview('{"text":"港口\\n灯亮了'), '港口\n灯亮了')
assert.equal(core.storyPreview('{"title":"开场"}'),'')
console.log('story authoring unit verification passed: blank start, autonomous request, manual continuity, variants, stale reviews and bounded generation')
